public class TiposDeAsignacion {
    public static void main(String[] args) {
        int numero1 = 10; // Asignación directa o simple
        System.out.println("El valor de numero1 es: " + numero1);
        
        int numero2 = numero1; // Asignación por referencia
        System.out.println("El valor de numero2 es: " + numero2);

        int numero3 = 5;
        System.out.println("El valor de numero3 es: " + numero3);
        
        numero3 += 2; // Asignación compuesta (equivalente a numero3 = numero3 + 2)
        System.out.println("El valor de numero3 es: " + numero3);
        
        int numero4 = 20;
        System.out.println("El valor de numero4 es: " + numero4);

        numero4 -= 5; // Asignación compuesta (equivalente a numero4 = numero4 - 5)
        System.out.println("El valor de numero4 es: " + numero4);
    
        int numero5 = 3;
        System.out.println("El valor de numero5 es: " + numero5);
        
        numero5 *= 4; // Asignación compuesta (equivalente a numero5 = numero5 * 4)
        System.out.println("El valor de numero5 es: " + numero5);
        
        int numero6 = 12;
        System.out.println("El valor de numero6 es: " + numero6);
        
        numero6 /= 3; // Asignación compuesta (equivalente a numero6 = numero6 / 3)
        System.out.println("El valor de numero6 es: " + numero6);
        
        int numero7 = 10;
        System.out.println("El valor de numero7 es: " + numero7);
    
        numero7 %= 3; // Asignación compuesta (equivalente a numero7 = numero7 % 3)
        System.out.println("El valor de numero7 es: " +numero7);
    }
    
}
